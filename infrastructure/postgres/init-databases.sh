#!/bin/bash
set -e

echo "Creating HRMS PostgreSQL databases (Employee, Payroll, Keycloak)..."

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
    CREATE USER ${EMPLOYEE_DB_USER} WITH PASSWORD '${EMPLOYEE_DB_PASSWORD}';
    CREATE DATABASE hrms_employee OWNER ${EMPLOYEE_DB_USER};
    GRANT ALL PRIVILEGES ON DATABASE hrms_employee TO ${EMPLOYEE_DB_USER};

    CREATE USER ${PAYROLL_DB_USER} WITH PASSWORD '${PAYROLL_DB_PASSWORD}';
    CREATE DATABASE hrms_payroll OWNER ${PAYROLL_DB_USER};
    GRANT ALL PRIVILEGES ON DATABASE hrms_payroll TO ${PAYROLL_DB_USER};

    CREATE USER ${KEYCLOAK_DB_USER} WITH PASSWORD '${KEYCLOAK_DB_PASSWORD}';
    GRANT ALL PRIVILEGES ON DATABASE keycloak TO ${KEYCLOAK_DB_USER};
    ALTER DATABASE keycloak OWNER TO ${KEYCLOAK_DB_USER};
EOSQL

echo "PostgreSQL databases created successfully!"
