
#!/bin/bash
set -e

echo "Creating HRMS MySQL databases..."

mysql -uroot -p"${MYSQL_ROOT_PASSWORD}" <<EOSQL

CREATE DATABASE IF NOT EXISTS hrms_leave CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE DATABASE IF NOT EXISTS hrms_notification CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE DATABASE IF NOT EXISTS hrms_recruitment CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE USER IF NOT EXISTS '${LEAVE_DB_USER}'@'%' IDENTIFIED BY '${LEAVE_DB_PASSWORD}';
CREATE USER IF NOT EXISTS '${NOTIFICATION_DB_USER}'@'%' IDENTIFIED BY '${NOTIFICATION_DB_PASSWORD}';
CREATE USER IF NOT EXISTS '${RECRUITMENT_DB_USER}'@'%' IDENTIFIED BY '${RECRUITMENT_DB_PASSWORD}';

GRANT ALL PRIVILEGES ON hrms_leave.* TO '${LEAVE_DB_USER}'@'%';
GRANT ALL PRIVILEGES ON hrms_notification.* TO '${NOTIFICATION_DB_USER}'@'%';
GRANT ALL PRIVILEGES ON hrms_recruitment.* TO '${RECRUITMENT_DB_USER}'@'%';

FLUSH PRIVILEGES;

EOSQL

echo "MySQL databases created successfully!"
